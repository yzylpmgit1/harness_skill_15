# 技能优化提示词（/optimize_skill 命令使用）
# 让 LLM 对技能的工作流正文进行优化，压缩 token、提升效率
# {skill_name}     替换为技能名称
# {optimize_goal}  替换为优化目标描述
# {original_body}  替换为原始正文
SKILL_OPTIMIZATION_PROMPT = """\
你是一个资深的提示词工程师，擅长大幅压缩 AI Agent 的技能工作流定义。

## 任务
对以下技能「{skill_name}」的工作流正文进行**大幅优化**，目标是在保留核心指导能力的前提下，尽可能压缩篇幅。

## 优化目标
{optimize_goal}

## 优化原则（按优先级排序）
1. **大幅压缩**：目标减少 30%-50% 的 token，不是微调，而是重写
2. **合并重组**：将分散在多处的同类规则合并为一个表格或列表，消除重复
3. **删除冗余**：去掉示例中的冗余解释、过渡性语句、显而易见的步骤说明
4. **结构化压缩**：用表格替代长段落，用短语替代完整句子，用缩进列表替代编号列表
5. **保留核心**：工具调用格式（JSON 参数）、兜底逻辑、关键工作流步骤必须保留
6. **格式保持**：保持 Markdown 格式（标题、表格、列表）

## 压缩技巧
- 将"工作流程"和"回答规范"中有重叠的部分合并
- 将多行描述压缩为一行要点
- 删除"适用场景"中的示例（Agent 通过关键词匹配即可触发，不需要示例）
- 用 `|` 分隔的表格行替代多行列表
- 合并相似的兜底规则为一条

## 原始正文
---
{original_body}
---

## 输出格式
请按以下格式输出，包含两部分：

[优化说明]
列出你做了哪些具体优化（3-5 条），包括：
- 具体删除了哪些内容
- 合并了哪些规则
- token 预计减少百分比
- 结构如何变化

[优化结果]
输出优化后的完整正文（从第一个 # 标题开始，不要包含 frontmatter）。
"""
